// A pull: the released ids as a source file in each language, the names, and the check for CI.
import { after, before, test } from "node:test";
import assert from "node:assert/strict";
import { execFile } from "node:child_process";
import { mkdtemp, readFile, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { promisify } from "node:util";
import { Api } from "../src/api.ts";
import { nameOf, pull } from "../src/pull.ts";
import { seedReleased, startFakeApi, type FakeApi } from "./fake-api.ts";

const run = promisify(execFile);
const action = fileURLToPath(new URL("../../action/pull/run.ts", import.meta.url));
let api: FakeApi;
let dir: string;
const client = () => new Api({ url: api.url, key: "read", project: "demo" });

before(async () => {
  api = await startFakeApi();
  seedReleased(api, "wool-blanket-red", { nb: "Rødt ullpledd", en: "Red wool blanket" });
  seedReleased(api, "gift-icon", { nb: "Gave", en: "Gift" });
  seedReleased(api, "404-illustration", { nb: "Ikke funnet", en: "Not found" });
  api.assets.set("draft-only", { id: "draft-only", preset: "flexible", alt: { nb: "Utkast", en: "Draft" }, versions: [] });
  dir = await mkdtemp(join(tmpdir(), "brua-pull-"));
});
after(() => api.close());

test("names are the ids in camel case, flat, and safe to start with", () => {
  assert.equal(nameOf("gift-theme-christmas-header"), "giftThemeChristmasHeader");
  assert.equal(nameOf("hero"), "hero");
  assert.equal(nameOf("404-illustration"), "_404Illustration");
});

test("TypeScript gets a const object and an id type, released assets only unless asked", async () => {
  const file = join(dir, "assets.ts");
  const result = await pull(client(), { out: file });
  const text = await readFile(file, "utf8");

  assert.deepEqual([result.language, result.count, result.changed], ["typescript", 3, true]);
  assert.match(text, /^\/\/ Generated by brua pull from the project demo\./);
  assert.match(text, /export const assets = \{\n  \/\*\* Ikke funnet · flexible, 400×300 \*\/\n  _404Illustration: "404-illustration",\n  \/\*\* Gave · flexible, 400×300 \*\/\n  giftIcon: "gift-icon",\n  \/\*\* Rødt ullpledd · flexible, 400×300 \*\/\n  woolBlanketRed: "wool-blanket-red",\n\} as const;/);
  assert.match(text, /export type AssetId = \(typeof assets\)\[keyof typeof assets\];/);
  assert.doesNotMatch(text, /draft-only/);

  const all = await pull(client(), { out: join(dir, "all.ts"), all: true });
  assert.equal(all.count, 4);
});

test("Swift, Kotlin, C# and JSON each get their own shape, with the namespace where the language wants one", async () => {
  await pull(client(), { out: join(dir, "Assets.swift") });
  await pull(client(), { out: join(dir, "Assets.kt"), namespace: "com.example.brand" });
  await pull(client(), { out: join(dir, "Assets.cs"), namespace: "Example.Brand" });
  await pull(client(), { out: join(dir, "assets.json") });

  assert.match(await readFile(join(dir, "Assets.swift"), "utf8"), /public enum BruaAssets: String, CaseIterable \{\n    \/\/\/ Ikke funnet · flexible, 400×300\n    case _404Illustration = "404-illustration"\n/);
  const kotlin = await readFile(join(dir, "Assets.kt"), "utf8");
  assert.match(kotlin, /\npackage com\.example\.brand\n/);
  assert.match(kotlin, /object BruaAssets \{\n(.*\n)*    const val giftIcon: String = "gift-icon"\n/);
  const csharp = await readFile(join(dir, "Assets.cs"), "utf8");
  assert.match(csharp, /\nnamespace Example\.Brand;\n/);
  assert.match(csharp, /public const string GiftIcon = "gift-icon";/);
  assert.match(csharp, /public const string _404Illustration = "404-illustration";/);
  const json = JSON.parse(await readFile(join(dir, "assets.json"), "utf8"));
  assert.deepEqual(json["gift-icon"], { name: "giftIcon", alt: "Gave", preset: "flexible", width: 400, height: 300, version: 1 });
});

test("a second pull is up to date, and check reports drift without writing", async () => {
  const file = join(dir, "assets.ts");
  assert.equal((await pull(client(), { out: file })).changed, false);

  seedReleased(api, "new-banner");
  const checked = await pull(client(), { out: file, check: true });
  assert.equal(checked.changed, true);
  assert.doesNotMatch(await readFile(file, "utf8"), /new-banner/, "check writes nothing");
  assert.equal((await pull(client(), { out: file })).changed, true);
  assert.match(await readFile(file, "utf8"), /newBanner: "new-banner"/);
});

test("the pull action writes the file and its outputs, and fails a check that is out of date", async () => {
  const file = join(dir, "action.swift");
  const outputs = join(dir, "outputs.txt");
  await writeFile(outputs, "");
  const env = { ...process.env, BRUA_API_URL: api.url, BRUA_API_KEY: "read", BRUA_PROJECT: "demo", BRUA_INPUT_OUT: file, GITHUB_OUTPUT: outputs };

  const first = await run(process.execPath, [action], { env });
  assert.match(first.stdout, /Wrote 4 assets to/);
  assert.match(await readFile(outputs, "utf8"), /^count=4\nchanged=true\n$/);

  seedReleased(api, "newer-still");
  const stale = await run(process.execPath, [action], { env: { ...env, BRUA_INPUT_CHECK: "true" } }).catch((e) => e);
  assert.equal(stale.code, 1);
  assert.match(stale.stdout, /::error::.*is out of date/);
});
