// A pull: the project's released asset ids as a source file for the app, so a reference to an asset that doesn't
// exist is a compile error and a rename shows up as a diff (SPEC.md 20.3). Names are the ids in camel case, flat:
// the platform doesn't know an id's hierarchy, and nesting by dash would clash when hero and hero-summer both exist.
import { readFile, writeFile } from "node:fs/promises";
import { extname } from "node:path";
import type { Api, Schemas } from "./api.ts";

export type Language = "typescript" | "swift" | "kotlin" | "csharp" | "json";

export interface PullOptions {
  /** The file to write; its extension picks the language unless one is given. */
  out: string;
  language?: Language;
  /** The Kotlin package or C# namespace. */
  namespace?: string;
  /** Include assets that have no released version yet. */
  all?: boolean;
  /** Compare with the file as it is and write nothing: the result says whether it is up to date. */
  check?: boolean;
}

export interface PullResult {
  file: string;
  language: Language;
  count: number;
  /** Whether the file differs from what the project has now: false means it was already up to date. */
  changed: boolean;
}

export interface PulledAsset {
  id: string;
  name: string;
  alt: string | null;
  preset: string;
  width: number | null;
  height: number | null;
  version: number | null;
}

const EXTENSIONS: Record<string, Language> = { ".ts": "typescript", ".swift": "swift", ".kt": "kotlin", ".cs": "csharp", ".json": "json" };

export async function pull(api: Api, options: PullOptions): Promise<PullResult> {
  const language = options.language ?? EXTENSIONS[extname(options.out).toLowerCase()];
  if (!language) throw new Error(`Say which language with --language: ${Object.keys(GENERATORS).join(", ")}; or name the file .ts, .swift, .kt, .cs or .json.`);
  if (!(language in GENERATORS)) throw new Error(`Unknown language "${language}": ${Object.keys(GENERATORS).join(", ")}.`);

  const listed = await api.listAssets();
  const assets = listed
    .filter((asset) => options.all || asset.liveVersion != null)
    .map(describe)
    .sort((a, b) => (a.id < b.id ? -1 : 1));
  const text = GENERATORS[language](assets, api.settings.project, options.namespace);

  let existing: string | undefined;
  try { existing = await readFile(options.out, "utf8"); } catch { /* new file */ }
  const changed = existing !== text;
  if (changed && !options.check) await writeFile(options.out, text);
  return { file: options.out, language, count: assets.length, changed };
}

function describe(asset: Schemas["AssetSummaryDto"]): PulledAsset {
  return { id: asset.id, name: nameOf(asset.id), alt: asset.alt ?? null, preset: asset.preset, width: asset.width ?? null, height: asset.height ?? null, version: asset.liveVersion ?? null };
}

/** gift-theme-christmas-header becomes giftThemeChristmasHeader; an id that starts with a digit gets an underscore. */
export function nameOf(id: string): string {
  const name = id.split("-").filter(Boolean).map((part, i) => (i === 0 ? part : part[0].toUpperCase() + part.slice(1))).join("");
  return /^\d/.test(name) ? `_${name}` : name;
}

const pascal = (name: string) => name.startsWith("_") ? name : name[0].toUpperCase() + name.slice(1);
const comment = (asset: PulledAsset) => [asset.alt, `${asset.preset}${asset.width && asset.height ? `, ${asset.width}×${asset.height}` : ""}`].filter(Boolean).join(" · ");
const header = (project: string, lead: string) => `${lead} Generated by brua pull from the project ${project}. Do not edit; run brua pull again.\n`;

const GENERATORS: Record<Language, (assets: PulledAsset[], project: string, namespace?: string) => string> = {
  typescript: (assets, project) => [
    header(project, "//"),
    "",
    `/** The released assets of ${project}, by id. */`,
    "export const assets = {",
    ...assets.map((a) => `  /** ${comment(a)} */\n  ${a.name}: "${a.id}",`),
    "} as const;",
    "",
    "export type AssetId = (typeof assets)[keyof typeof assets];",
    "",
  ].join("\n"),

  swift: (assets, project) => [
    header(project, "//"),
    "",
    `/// The released assets of ${project}, by id.`,
    "public enum BruaAssets: String, CaseIterable {",
    ...assets.map((a) => `    /// ${comment(a)}\n    case ${a.name} = "${a.id}"`),
    "}",
    "",
  ].join("\n"),

  kotlin: (assets, project, namespace) => [
    header(project, "//"),
    ...(namespace ? [``, `package ${namespace}`] : []),
    "",
    `/** The released assets of ${project}, by id. */`,
    "object BruaAssets {",
    ...assets.map((a) => `    /** ${comment(a)} */\n    const val ${a.name}: String = "${a.id}"`),
    "}",
    "",
  ].join("\n"),

  csharp: (assets, project, namespace) => [
    header(project, "//"),
    ...(namespace ? [``, `namespace ${namespace};`] : []),
    "",
    `/// <summary>The released assets of ${project}, by id.</summary>`,
    "public static class BruaAssets",
    "{",
    ...assets.map((a) => `    /// <summary>${comment(a).replace(/</g, "&lt;").replace(/>/g, "&gt;")}</summary>\n    public const string ${pascal(a.name)} = "${a.id}";`),
    "}",
    "",
  ].join("\n"),

  json: (assets) => JSON.stringify(Object.fromEntries(assets.map(({ id, ...rest }) => [id, rest])), null, 2) + "\n",
};
